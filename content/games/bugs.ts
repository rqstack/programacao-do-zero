/** Roda a função do código (linhas) com os argumentos. Usado para calcular as respostas esperadas. */
export function runBugCode(code: readonly string[], fn: string, args: unknown[]): unknown {
  const f = new Function(`${code.join("\n")}\n;return ${fn};`)() as (...a: unknown[]) => unknown;
  return f(...structuredClone(args));
}

/** Código corrigido (troca só a linha do bug). */
export function fixedCode(b: BugCase): string[] {
  return b.code.map((l, i) => (i === b.line - 1 ? b.fix : l));
}
